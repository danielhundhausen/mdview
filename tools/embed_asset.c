#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

/* Build-time binary-to-C conversion; normal builds need only a C compiler. */
static int array(FILE *out, const char *path, const char *name, int terminate) {
    FILE *in = fopen(path, "rb");
    if (!in) { perror(path); return 0; }
    fprintf(out, "static const unsigned char %s[] = {\n", name);
    size_t count = 0; int c;
    while ((c = fgetc(in)) != EOF) {
        fprintf(out, "0x%02x,", (unsigned)c);
        if (++count % 16 == 0) fputc('\n', out);
    }
    int failed = ferror(in);
    if (fclose(in)) failed = 1;
    if (terminate) fputs("0x00,", out);
    fputs("\n};\n", out);
    return !failed && !ferror(out);
}

int main(int argc, char **argv) {
    if (argc < 4 || argc > 5 || (argc == 5 && strcmp(argv[4], "--text"))) {
        fputs("Usage: embed_asset INPUT SYMBOL OUTPUT [--text]\n", stderr); return 1;
    }
    if (!*argv[2]) { fputs("embed_asset: empty C symbol\n", stderr); return 1; }
    for (const char *p = argv[2]; *p; ++p) {
        if (!(isalpha((unsigned char)*p) || *p == '_' ||
              (p != argv[2] && isdigit((unsigned char)*p)))) {
            fputs("embed_asset: invalid C symbol\n", stderr); return 1;
        }
    }
    FILE *out = fopen(argv[3], "wb");
    if (!out) { perror(argv[3]); return 1; }
    fputs("/* Generated by tools/embed_asset.c. Do not edit. */\n", out);
    int good = array(out, argv[1], argv[2], argc == 5);
    if (fclose(out)) good = 0;
    if (!good) { remove(argv[3]); fputs("embed_asset: asset conversion failed\n", stderr); }
    return good ? 0 : 1;
}
